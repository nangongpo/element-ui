var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '../..');
var varPath = path.join(root, 'packages/theme-chalk/src/common/var.scss');
var cssPath = path.join(root, 'lib/theme-chalk/index.css');
var fallbackCssPath = path.join(root, 'packages/theme-chalk/lib/index.css');
var outputPath = path.join(root, 'examples/components/theme/loader/local-theme-data.js');

var globalTypeMap = {
  color: 'color',
  fontSize: 'typography',
  fontWeight: 'typography',
  fontLineHeight: 'typography',
  borderRadius: 'border',
  boxShadow: 'border'
};

var componentNameMap = {
  msgbox: 'message-box'
};

function readFile(file) {
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
}

function escapeString(value) {
  return JSON.stringify(value);
}

function stripValue(value) {
  return value
    .replace(/\s*!default\s*;?\s*$/, '')
    .replace(/\s*;?\s*$/, '')
    .trim();
}

function getComponentName(key) {
  var name = key.replace(/^\$--/, '').split('-')[0];
  return componentNameMap[name] || name;
}

function addConfig(groups, name, config) {
  if (!groups[name]) {
    groups[name] = {
      name: name,
      config: []
    };
  }
  groups[name].config.push(config);
}

function parseVars(source) {
  var lines = source.split(/\r?\n/);
  var groups = {};
  var defaults = {};
  var meta = null;

  lines.forEach(function(line) {
    var metaMatch = line.match(/^\s*\/\/\/?\s*([A-Za-z]+)\|([^|]*)\|([^|]*)\|(\d+)/);
    if (metaMatch) {
      meta = {
        type: metaMatch[1],
        global: metaMatch[2] === '1',
        category: metaMatch[3],
        order: Number(metaMatch[4])
      };
      return;
    }

    var varMatch = line.match(/^\s*(\$--[A-Za-z0-9-]+)\s*:\s*(.+)$/);
    if (!varMatch) {
      if (meta && line.trim()) meta = null;
      return;
    }

    var key = varMatch[1];
    var value = stripValue(varMatch[2]);
    defaults[key] = value;

    if (!meta) return;

    var groupName = meta.global ? globalTypeMap[meta.type] : getComponentName(key);
    if (!groupName) {
      meta = null;
      return;
    }

    addConfig(groups, groupName, {
      name: meta.global,
      key: key,
      value: value,
      type: meta.type,
      category: meta.category,
      order: meta.order
    });
    meta = null;
  });

  return Object.keys(groups).map(function(name) {
    return groups[name];
  }).sort(function(a, b) {
    if (a.name === 'color') return -1;
    if (b.name === 'color') return 1;
    if (a.name === 'typography') return -1;
    if (b.name === 'typography') return 1;
    if (a.name === 'border') return -1;
    if (b.name === 'border') return 1;
    return a.name > b.name ? 1 : -1;
  }).map(function(group) {
    group.config.sort(function(a, b) {
      return a.order - b.order || (a.key > b.key ? 1 : -1);
    });
    return group;
  });
}

var source = readFile(varPath);
var css = readFile(cssPath) || readFile(fallbackCssPath);
var config = parseVars(source);

if (!css) {
  throw new Error('Theme CSS not found. Please run npm run build:theme before build-theme-config.');
}

var output = '/* eslint-disable */\n' +
  '/* Automatically generated by ./build/bin/build-theme-config.js */\n\n' +
  'export const themeConfig = ' + JSON.stringify(config, null, 2) + ';\n\n' +
  'export const themeCss = ' + escapeString(css) + ';\n';

fs.writeFileSync(outputPath, output);
console.log('[build theme config] DONE:', outputPath);
